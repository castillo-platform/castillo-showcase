#!/usr/bin/env python3
"""Builds views.js from the helpers' views-*.json: per app its 3–4 views with title, text and the
desktop, tablet and phone screenshot paths (shots/<prefix>-<view>-<device>.webp). Missing files
are left out, so a view without a tablet shot shows no tablet."""
import json, pathlib, sys
root = pathlib.Path(__file__).resolve().parent.parent
if len(sys.argv) != 2:
    sys.exit('usage: views.py <folder with views-*.json>')
src = pathlib.Path(sys.argv[1])
alias = {'familien-todo': 'zuhause'}  # shot prefix -> app id on the page
out = {}
for f in sorted(src.glob('views-*.json')):
    for prefix, views in json.loads(f.read_text()).items():
        rows = []
        for v in views:
            row = {'title': v['title'], 'text': v['text']}
            for dev in ('desktop', 'tablet', 'phone'):
                p = root / 'shots' / f"{prefix}-{v['view']}-{dev}.webp"
                if p.exists():
                    row[dev] = f'shots/{p.name}'
            rows.append(row)
        out[alias.get(prefix, prefix)] = rows
(root / 'views.js').write_text('// Generated by tools/views.py from the view lists. Do not edit by hand.\nwindow.CASTILLO_VIEWS = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n')
print({k: len(v) for k, v in out.items()})
